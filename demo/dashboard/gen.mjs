// The TypeScript demo can't include_str! the dashboard, so it imports it from a generated module.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, 'index.html'), 'utf8');
writeFileSync(join(here, '../typescript/src/page.gen.ts'), `// Generated by demo/dashboard/gen.mjs. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
